pub fn item_kind(name: &str) -> Option<i32> {
    let name = name.trim().to_ascii_lowercase();
    let name = name.strip_prefix("item_kind_").unwrap_or(&name);
    ITEM_KINDS
        .iter()
        .find(|(known, _)| *known == name)
        .map(|(_, kind)| *kind)
}

pub fn item_name(kind: i32) -> Option<&'static str> {
    ITEM_KINDS
        .iter()
        .find(|(_, known)| *known == kind)
        .map(|(name, _)| *name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn items_resolve_by_the_games_names() {
        assert_eq!(item_kind("killsword"), Some(63));
        assert_eq!(item_kind("ITEM_KIND_PICKELOBJECT"), Some(0x1ae));
        assert_eq!(item_kind(" Galleom "), Some(367));
        assert_eq!(item_kind("mario"), None);
        assert_eq!(item_name(63), Some("killsword"));
        for (index, (name, kind)) in ITEM_KINDS.iter().enumerate() {
            assert!(ITEM_KINDS[index + 1..].iter().all(|(other, number)| other != name && number != kind), "{name}");
        }
    }
}
